#define FRAME_DURATION_MS 150
static uint32_t anim_timer = 0;
static uint8_t cycle_index = 0;
static const uint8_t frame_sequence[] = {0, 1, 2, 3, 4, 3, 2, 1, 0, 1, 2, 3, 4, 3, 2, 1, 0, 1, 2, 3, 4, 3, 2, 1, 0, 1, 2, 3, 5, 5, 3, 2, 1}; 
#define SEQUENCE_LEN 32

// Restore the initialization to ensure correct orientation
oled_rotation_t oled_init_user(oled_rotation_t rotation) {
    return OLED_ROTATION_0; // Change to OLED_ROTATION_180 if screen is upside down
}

bool oled_task_user(void) {

    if (shock_active && timer_elapsed32(shock_timer) >= SHOCK_DURATION_MS) {
        shock_active = false;
    }
    if (!shock_active && timer_elapsed32(anim_timer) > FRAME_DURATION_MS) {
        anim_timer = timer_read32();
        cycle_index = (cycle_index + 1) % SEQUENCE_LEN;
    }

    oled_set_cursor(0, 0);
    oled_write_P(PSTR("Arnaan Shah"), false);

    oled_set_cursor(0, 1);
    oled_write_P(PSTR("Vantapad"), false);

    oled_set_cursor(0, 2);
    switch (get_highest_layer(layer_state)) {
        case _BASE:   oled_write_P(PSTR("Layer 1"), false); break;
        case _LAYER1: oled_write_P(PSTR("Layer 2"), false); break;
        case _LAYER2: oled_write_P(PSTR("Layer 3"), false); break;
    }

    oled_set_cursor(0, 3);
    if (auto_clicker_active) {
        oled_write_P(PSTR("AutoClick:ON "), false);
    } else {
        oled_write_P(PSTR("AutoClick:OFF"), false);
    }
    
    uint8_t frame_to_show = shock_active ? 6 : frame_sequence[cycle_index];
    const char* bitmap = (const char*)pgm_read_ptr(&epd_bitmap_allArray[frame_to_show]);
    
    for (uint8_t i = 0; i < 4; i++) {
        oled_set_cursor(13, i); 
        oled_write_raw_P(bitmap + (i * 45), 45);
    }

    return false;
}
